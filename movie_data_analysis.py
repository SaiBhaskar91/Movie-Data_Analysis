import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("/content/imdb_movie_dataset.csv")

yearly_avg = df.groupby('Year')['Rating'].mean()

plt.figure(figsize=(10,6))
plt.plot(yearly_avg.index, yearly_avg.values, marker='o', color='green')
plt.title('Average Rating by Year', fontsize=14)
plt.xlabel('Year')
plt.ylabel('Average Rating')
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()