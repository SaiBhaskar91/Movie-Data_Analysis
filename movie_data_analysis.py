import pandas as pd

df=pd.read_csv('/content/imdb_movie_dataset.csv')

df.info()

df.describe()

df.head(2)

df.tail(5)

df.isnull().sum()

missing_value=(df.isnull().sum()/len(df))*100
print(missing_value)

df['Revenue (Millions)']=df['Revenue (Millions)'].fillna(df['Revenue (Millions)'].median())

df['Metascore']=df['Metascore'].fillna(df['Metascore'].median())

df.duplicated().sum()

df.drop_duplicates(inplace=True)

tar="Rating"
ncol=df.select_dtypes(include=['float64','int64']).columns
for col in ncol:
  if col!=tar:
    val=df[tar].corr(df[col])
    print(f"{tar} vs {col}: {val:.2f}")

import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("/content/imdb_movie_dataset.csv")

top10_revenue = df.sort_values('Revenue (Millions)', ascending=False).head(10)

plt.figure(figsize=(10,6))
plt.bar(top10_revenue['Title'], top10_revenue['Revenue (Millions)'], color='steelblue')
plt.title('Top 10 Highest Grossing Movies', fontsize=14)
plt.xlabel('Movie Title')
plt.ylabel('Revenue (Millions)')
plt.tight_layout()
plt.show()

